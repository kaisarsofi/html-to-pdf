// Turns the bundled font files (static WOFF from the @fontsource devDependencies) into
// lazily-imported base64 modules, so a consumer needs no bundler configuration to ship them
// (no asset URLs, no file copying) and the repo needs no font binaries.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src', 'fonts', 'data');
fs.mkdirSync(out, { recursive: true });

const filesDir = (pkg) => path.join(path.dirname(require.resolve(`${pkg}/package.json`)), 'files');

// [fontsource package, source file prefix, subsets, weights]
const sources = [
  ['@fontsource/inter', 'inter', ['latin', 'latin-ext'], [300, 400, 500, 600, 700]],
  ['@fontsource/noto-sans', 'noto-sans', ['latin', 'latin-ext', 'greek', 'cyrillic', 'devanagari', 'vietnamese'], [400, 700]],
];

const entries = [];
for (const [pkg, prefix, subsets, weights] of sources) {
  const dir = filesDir(pkg);
  for (const subset of subsets) {
    for (const weight of weights) {
      const file = `${prefix}-${subset}-${weight}-normal.woff`;
      const name = `${prefix}-${subset}-${weight}`;
      const base64 = fs.readFileSync(path.join(dir, file)).toString('base64');
      fs.writeFileSync(
        path.join(out, `${name}.ts`),
        `// Generated by scripts/build-fonts.mjs from ${pkg}/files/${file}. Do not edit.\nconst data: string = '${base64}';\nexport default data;\n`
      );
      entries.push(name);
    }
  }
}

// One literal dynamic import per module, so bundlers can see and split every one of them.
const manifest =
  '// Generated by scripts/build-fonts.mjs. Do not edit.\n' +
  'export const fontModules: Record<string, () => Promise<string>> = {\n' +
  entries.map((n) => `  '${n}': () => import('./${n}.js').then((m) => m.default),`).join('\n') +
  '\n};\n';
fs.writeFileSync(path.join(out, 'manifest.ts'), manifest);
console.log(`wrote ${entries.length} font modules`);
